export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Total width of a string in glyph cells (1-cell letter spacing). */
export function pixelTextWidth(text: string): number {
  if (!text.length) return 0;
  return text.length * (GLYPH_W + 1) - 1;
}

/** Cells of a string → [{x, y}] in glyph-space (y grows downward). */
export function pixelTextCells(text: string): { x: number; y: number }[] {
  const cells: { x: number; y: number }[] = [];
  const upper = text.toUpperCase();
  let ox = 0;
  for (const ch of upper) {
    const glyph = PIXEL_FONT[ch] ?? PIXEL_FONT["-"];
    for (let y = 0; y < GLYPH_H; y++) {
      const row = glyph[y];
      for (let x = 0; x < GLYPH_W; x++) {
        if (row[x] === "#") cells.push({ x: ox + x, y });
      }
    }
    ox += GLYPH_W + 1;
  }
  return cells;
}

/** Draw a bitmap string onto a 2D context. Returns pixel width used. */
export function drawPixelText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  cell: number,
  color: string
): number {
  const cells = pixelTextCells(text);
  ctx.fillStyle = color;
  for (const c of cells) {
    ctx.fillRect(x + c.x * cell, y + c.y * cell, cell, cell);
  }
  return pixelTextWidth(text) * cell;
}
